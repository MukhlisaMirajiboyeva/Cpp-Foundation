/* Задача 1: Проверка на палиндром
Условие: Пользователь вводит слово. Программа должна определить, 
является ли оно палиндромом (читается одинаково в обоих направлениях, например: "шалаш", "радар").

Объяснение алгоритма: Чтобы проверить слово, нам нужно сравнить первую букву с последней, 
вторую с предпоследней и так далее.
- Индекс первой буквы: 0, последней: длина - 1.
- Индекс второй буквы: 1, предпоследней: длина - 2.
- Общая формула для сравнения: s[i] и s[длина - 1 - i]. */




#include <iostream>
#include <string>
#include <algorithm> // для работы с регистрами, если нужно

using namespace std;

int main() {
    string s;
    cout << "Введите слово: ";
    cin >> s;

    bool isPalindrome = true;
    int n = s.length();

    // Идем до середины строки
    for (int i = 0; i < n / 2; i++) {
        // Сравниваем симметричные символы
        if (s[i] != s[n - 1 - i]) {
            isPalindrome = false; // Если хоть одна пара не совпала — это не палиндром
            break;
        }
    }

    if (isPalindrome) cout << "Это палиндром!" << endl;
    else cout << "Это не палиндром." << endl;

    return 0;
}