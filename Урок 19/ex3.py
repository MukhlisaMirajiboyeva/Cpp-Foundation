'''
Задача 3. «Орел и Решка» (Random)
Задание: Программа «подбрасывает монетку» (генерирует случайное число 0 или 1, 
или выбирает из списка ["Орел", "Решка"]).
- Спросите у пользователя: «Орел или Решка?».
- Если угадал — «Вы победили!», если нет — «Попробуйте снова».
'''

import random

# 1. Список вариантов
coins = ["Орел", "Решка"]

# 2. Компьютер делает выбор
computer_choice = random.choice(coins)

# 3. Пользователь делает выбор
user_choice = input("Орел или Решка? (Введите точно так же): ")

print(f"Выпало: {computer_choice}")

# 4. Сравниваем
if user_choice == computer_choice:
    print("🎉 Вы победили!")
else:
    print("😔 Не угадали. Попробуйте снова.")