total_sum = 0

print("Введите 5 чисел. Отрицательные пропускаются, 0 - выход.")

for i in range(5):
    num = int(input(f"Введите число {i+1}: "))

    if num == 0:
        print("Введен ноль. Остановка подсчета.")
        break  # Полный выход из цикла

    if num < 0:
        print("Отрицательное число, пропускаем...")
        continue  # Пропуск только этого числа, идем к следующему

    total_sum += num  # Эта строка сработает, только если не было break или continue

print(f"Итоговая сумма: {total_sum}")