# 1. Исходная "грязная" строка
# Тут есть пробелы по краям, разный регистр и слово "ошибка"
raw_data = "   Привет, это тестовая ОШИБКА   "

# 2. Применяем .strip() — убираем пробелы по бокам
step1 = raw_data.strip() 
# Результат: "Привет, это тестовая ОШИБКА"

# 3. Применяем .lower() — делаем всё маленькими буквами (удобно для поиска)
step2 = step1.lower()
# Результат: "привет, это тестовая ошибка"

# 4. Применяем .replace() — исправляем слово "ошибка" на "программа"
step3 = step2.replace("ошибка", "программа")
# Результат: "привет, это тестовая программа"

# 5. Применяем .upper() — представим, что нам нужен важный заголовок
final_text = step3.upper()
# Результат: "ПРИВЕТ, ЭТО ТЕСТОВАЯ ПРОГРАММА"

# 6. Применяем .split() — рубим строку на отдельные слова
words_list = final_text.split() 
# По умолчанию split() рубит по пробелам
# Результат: ['ПРИВЕТ,', 'ЭТО', 'ТЕСТОВАЯ', 'ПРОГРАММА']

# Вывод итогов
print(f"Оригинал: '{raw_data}'")
print(f"После чистки: '{final_text}'")
print(f"Список слов: {words_list}")
print(f"Количество символов (len): {len(final_text)}")