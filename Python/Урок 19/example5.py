import math

# Округление
print(math.ceil(4.2))   # 5 (Потолок - округление вверх) 
print(math.floor(4.9))  # 4 (Пол - округление вниз)

# Степени и корни
print(math.pow(2, 3))   # 2 в степени 3 = 8.0 
print(math.sqrt(144))   # Корень из 144 = 12.0 

# Факториал (произведение чисел от 1 до n)
print(math.factorial(3)) # 1 * 2 * 3 = 6 