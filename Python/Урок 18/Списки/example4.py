heroes = ["Железный человек", "Тор", "Халк", "Человек-паук", "Капитан Америка"]

# Обычный доступ
first = heroes[0] 
last = heroes[-1]

# Сложный срез: берем героев с 1 по 3 (Тор и Халк)
team_a = heroes[1:3]

# Срез с конца: последние три героя
team_b = heroes[-3:]

print(f"Первый: {first}, Последний: {last}")
print(f"Команда А: {team_a}")
print(f"Команда Б: {team_b}")