# Создаем начальный список
fruits = ["яблоко", "банан"]
print(f"0. Старт: {fruits}")

# 1. append — Добавляем ОДИН элемент в самый конец
fruits.append("вишня")
# ["яблоко", "банан", "вишня"]

# 2. extend — Добавляем сразу НЕСКОЛЬКО элементов (другой список) в конец
fruits.extend(["апельсин", "киви"])
# ["яблоко", "банан", "вишня", "апельсин", "киви"]

# 3. insert — Вставляем элемент в конкретное место (индекс, значение)
fruits.insert(1, "манго") 
# Теперь "манго" на 1-м месте, а остальные подвинулись
# ["яблоко", "манго", "банан", "вишня", "апельсин", "киви"]

# 4. index — Узнаем, на каком месте (под каким индексом) находится элемент
pos = fruits.index("вишня")
print(f"Вишня находится на позиции: {pos}") # Выведет 3

# 5. count — Считаем, сколько раз встречается элемент в списке
fruits.append("яблоко") # Добавим еще одно для счета
cnt = fruits.count("яблоко")
print(f"Яблок в корзине: {cnt}") # Выведет 2

# 6. remove — Удаляем элемент по его ИМЕНИ (первое совпадение)
fruits.remove("банан")
# ["яблоко", "манго", "вишня", "апельсин", "киви", "яблоко"]

# 7. pop — Удаляем элемент по ИНДЕКСУ и можем его «забрать» себе
last_item = fruits.pop() # Если не указать индекс, удалит последний
print(f"Мы достали из корзины последнее яблоко: {last_item}")
# ["яблоко", "манго", "вишня", "апельсин", "киви"]

# 8. sort — Сортируем список (по алфавиту или по возрастанию чисел)
fruits.sort()
# ["апельсин", "вишня", "киви", "манго", "яблоко"]

# 9. reverse — Просто переворачиваем список задом наперед
fruits.reverse()
# ["яблоко", "манго", "киви", "вишня", "апельсин"]

print(f"Итог перед очисткой: {fruits}")

# 10. clear — Полностью очищаем список
fruits.clear()
print(f"Корзина после clear: {fruits}") # []