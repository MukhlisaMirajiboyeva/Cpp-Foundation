# 1. Список дел (строки)
tasks = ["Учеба", "Завтрак", "Спорт"]

# --- ДОБАВЛЕНИЕ ---
tasks.append("Чтение")
tasks.insert(1, "Почистить зубы")
tasks.extend(["Магазин", "Ужин"])

# --- ПОИСК И АНАЛИЗ (Используем функции) ---
print(f"Всего задач: {len(tasks)}")           # len() - длина
print(f"Первая по алфавиту: {min(tasks)}")    # min() - для строк это начало алфавита
print(f"Последняя по алфавиту: {max(tasks)}") # max() - конец алфавита

# --- СОРТИРОВКА (Два способа) ---
# Способ А: sorted() - создает НОВЫЙ список, оригинал не меняется
sorted_tasks = sorted(tasks) 
print(f"Новый отсортированный список: {sorted_tasks}")
print(f"Оригинал остался прежним: {tasks}")

# Способ Б: .sort() - меняет сам оригинал "на месте"
tasks.sort()
print(f"Оригинал теперь отсортирован: {tasks}")

# --- ПРИМЕР С ЧИСЛАМИ (Для лучшего понимания min/max) ---
scores = [45, 89, 12, 100, 5]
print(f"\nЧисла: {scores}")
print(f"Минимальное: {min(scores)}") # 5
print(f"Максимальное: {max(scores)}") # 100
print(f"Сумма всех: {sum(scores)}")    # Бонус: сумма чисел