# 1. Создаем словарь: Блюдо (ключ) -> Цена (значение)
menu = {
    "Кофе": 15000,
    "Чай": 10000,
    "Круассан": 20000,
    "Сэндвич": 35000
}

# 2. Обращение к элементу по ключу
print(f"Цена кофе: {menu['Кофе']} сум")

# 3. Добавление нового элемента
menu["Пирожное"] = 18000

# 4. Изменение существующего значения (скидка на сэндвич)
menu["Сэндвич"] = 30000

# 5. Метод get() — безопасный поиск
# Если мы просто напишем menu["Борщ"], программа сломается. 
# Метод get вернет "Нет в наличии", если блюда нет.
check_dish = menu.get("Борщ", "Нет в наличии")
print(f"Поиск борща: {check_dish}")

# 6. Метод pop() — удаление и возврат значения
removed_price = menu.pop("Чай")
print(f"Чай удален из меню. Его цена была: {removed_price}")

# 7. Работа с ключами и значениями отдельно
print(f"Список всех блюд: {list(menu.keys())}")
print(f"Список всех цен: {list(menu.values())}")

# 8. Итерация по словарю
# Выводим красивое меню через цикл
print("--- НАШЕ МЕНЮ ---")
for dish, price in menu.items():
    print(f"🍴 {dish} ........ {price} сум")