# Создаем список книг (Списки)
books = ["Гарри Поттер", "Властелин Колец", "Маленький принц"]

# --- РАБОТА СО СПИСКОМ ---
books.append("Дюна")              # Добавили в конец
books.insert(0, "Ведьмак")        # Вставили в самое начало
books.sort()                      # Отсортировали по алфавиту
print(f"В библиотеке {len(books)} книг: {books}")

# --- РАБОТА СО СЛОВАРЕМ (Инфо о книге) ---
book_info = {
    "title": "Дюна",
    "author": "Фрэнк Герберт",
    "year": 1965
}

# Обновляем данные (Метод update)
book_info.update({"pages": 600, "genre": "Sci-Fi"}) 

# Удаляем элемент (Метод pop)
removed_value = book_info.pop("year") 
print(f"Из инфо удален год ({removed_value}). Текущий словарь: {book_info}")

# Получаем все ключи и значения отдельно
print(f"Ключи словаря: {list(book_info.keys())}")
print(f"Значения словаря: {list(book_info.values())}")

# --- РАБОТА С КОРТЕЖЕМ ---
# Допустим, книга стоит на полке №5, ряд №3
location = (5, 3) 
print(f"Книга находится на полке {location[0]}, ряд {location[1]}")