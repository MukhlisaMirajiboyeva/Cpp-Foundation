# --- ЧАСТЬ 1: СЫРЫЕ ДАННЫЕ (Как они пришли к нам) ---
# Названия товаров (Список)
gadgets = ["iPhone 15", "Samsung S24", "MacBook Air", "Sony PS5"]

# Цены в долларах (Кортеж - потому что менять цены нельзя)
prices = (999, 899, 1200, 499)

# Новое поступление (Список вложенных списков: Товар - Цена)
new_arrival = [
    ["AirPods", 199],
    ["Apple Watch", 399]
]

print("--- 1. Исходные данные получены ---")

# --- ЧАСТЬ 2: МАГИЯ ПРЕОБРАЗОВАНИЯ ---

# A. Создаем основной каталог цен (Сшиваем два списка через zip)
# zip берет 1-й элемент оттуда и 1-й отсюда, склеивает их в пару.
# dict превращает эти пары в словарь.
catalog = dict(zip(gadgets, prices))

print(f"Каталог после zip(): {catalog}")

# B. Превращаем список новичков в словарь напрямую
# Здесь zip не нужен, так как данные уже лежат парами [Ключ, Значение]
new_items_dict = dict(new_arrival)

print(f"Словарь новинок: {new_items_dict}")

# C. Объединяем всё в общий магазин
catalog.update(new_items_dict)

print(f"\n--- 2. Полный каталог сформирован ({len(catalog)} товаров) ---")

# --- ЧАСТЬ 3: ИСПОЛЬЗОВАНИЕ ДАННЫХ ---

# Задача: Найти самый дорогой товар
# Трюк: max ищет по ключам, но мы попросим искать по значениям (ценам)
most_expensive = max(catalog, key=catalog.get) 
max_price = catalog[most_expensive]

print(f"💎 Самый дорогой лот: {most_expensive} (${max_price})")

# Задача: Экспорт данных обратно в список (например, для печати чека)
# Метод .items() достает пары, а list() делает из них список кортежей
export_list = list(catalog.items())

print("\n--- 3. Экспорт для печати (Словарь -> Список) ---")
print(export_list)
# Результат: [('iPhone 15', 999), ('Samsung S24', 899)...]