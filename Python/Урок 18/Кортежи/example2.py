# Создаем кортеж с данными: Широта, Долгота, Название города, Год основания
location = (41.29, 69.24, "Ташкент", 2200)

# 1. Положительные индексы (Слева направо, начиная с 0)
city_name = location[2]   # "Ташкент"
latitude = location[0]    # 41.29
print(f"Город: {city_name}, Широта: {latitude}")

# 2. Отрицательные индексы (Справа налево, начиная с -1)
year = location[-1]       # 2200 (последний элемент)
longitude = location[-3]  # 69.24
print(f"Основан в {year} году, Долгота: {longitude}")

# 3. Срезы (Slicing) — получаем новый маленький кортеж
coords = location[0:2]    # Берем элементы с индексами 0 и 1
print(f"Только координаты: {coords}") # (41.29, 69.24)

# 4. Распаковка кортежа (Unpacking) — очень удобный способ в Python
lat, lon, city, age = location
print(f"Распакованные данные: {city} находится на {lat} широте")